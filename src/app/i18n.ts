const TEXTOS = { es, en };

function idiomaInicial(): Idioma {
  try {
    const guardado = localStorage.getItem('chamuyo-idioma');
    if (guardado === 'es' || guardado === 'en') return guardado;
  } catch {
    /* sin almacenamiento */
  }
  return navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export const idioma = signal<Idioma>(idiomaInicial());
export const t = computed(() => TEXTOS[idioma()]);

export function cambiarIdioma(nuevo: Idioma): void {
  idioma.set(nuevo);
  document.documentElement.lang = nuevo;
  try {
    localStorage.setItem('chamuyo-idioma', nuevo);
  } catch {
    /* sin almacenamiento */
  }
}
